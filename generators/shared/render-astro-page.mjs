/**
 * Render a complete .astro page from a list of section invocations.
 *
 * Each section is { component: 'HeroSplit', props: {...} }. The renderer
 * collects unique component names, emits imports, serializes props as JSON
 * frontmatter consts, and stitches the body with <Comp {...props} /> tags.
 *
 * `headHtml` and `extraScripts` are pre-rendered strings — the producer is
 * responsible for escaping. This keeps the renderer dumb.
 */
export function renderAstroPage({
  lang = "en",
  dataTheme = "ganhuo-saas",
  headHtml = "",
  cssImport = "../styles/global.css",
  componentsImportRoot = "../components/sections",
  bodyClass = "min-h-screen bg-base-100 text-base-content antialiased overflow-x-hidden",
  sections = [],
  metadata = null,
}) {
  const uniqueComponents = [...new Set(sections.map((s) => s.component))];
  const imports = uniqueComponents.map(
    (name) =>
      `import ${name} from ${JSON.stringify(`${componentsImportRoot}/${name}.astro`)};`
  );

  const propIds = sections.map((s, i) => `${lcFirst(s.component)}${i}Props`);
  const propLines = sections.map(
    (s, i) => `const ${propIds[i]} = ${JSON.stringify(s.props ?? {}, null, 2)};`
  );

  const metadataLine = metadata
    ? `const landerpilot = ${JSON.stringify(metadata, null, 2)};\nvoid landerpilot;`
    : "";

  const sectionTags = sections
    .map((s, i) => `    <${s.component} {...${propIds[i]}} />`)
    .join("\n");

  return [
    "---",
    "// Generated by LanderPilot. Edit source data under .ganhuo/ before regenerating.",
    `import ${JSON.stringify(cssImport)};`,
    ...imports,
    "",
    ...propLines,
    metadataLine,
    "---",
    "",
    "<!doctype html>",
    `<html lang=${attr(lang)} data-theme=${attr(dataTheme)}>`,
    "  <head>",
    indent(headHtml, 4),
    '    <link rel="icon" type="image/svg+xml" href="/favicon.svg" />',
    "  </head>",
    `  <body class=${attr(bodyClass)}>`,
    sectionTags,
    "  </body>",
    "</html>",
    "",
  ].join("\n");
}

export function renderHeadHtml({
  title,
  description,
  canonicalUrl,
  ogImage,
  schemaJson,
  organizationSchemaJson,
  preloadFonts = ["fraunces-variable.woff2", "hanken-grotesk-variable.woff2"],
  extraTags = [],
} = {}) {
  const lines = [
    '<meta charset="utf-8" />',
    '<meta name="viewport" content="width=device-width, initial-scale=1" />',
  ];
  for (const font of preloadFonts) {
    lines.push(
      `<link rel="preload" as="font" type="font/woff2" href="/fonts/${escapeHtmlAttr(font)}" crossorigin />`
    );
  }
  if (title) lines.push(`<title>${escapeHtmlText(title)}</title>`);
  if (description)
    lines.push(`<meta name="description" content="${escapeHtmlAttr(description)}" />`);
  if (canonicalUrl)
    lines.push(`<link rel="canonical" href="${escapeHtmlAttr(canonicalUrl)}" />`);
  lines.push('<meta property="og:type" content="website" />');
  if (title)
    lines.push(`<meta property="og:title" content="${escapeHtmlAttr(title)}" />`);
  if (description)
    lines.push(
      `<meta property="og:description" content="${escapeHtmlAttr(description)}" />`
    );
  if (canonicalUrl)
    lines.push(`<meta property="og:url" content="${escapeHtmlAttr(canonicalUrl)}" />`);
  if (ogImage)
    lines.push(`<meta property="og:image" content="${escapeHtmlAttr(ogImage)}" />`);
  lines.push('<meta name="twitter:card" content="summary_large_image" />');
  if (title)
    lines.push(`<meta name="twitter:title" content="${escapeHtmlAttr(title)}" />`);
  if (description)
    lines.push(
      `<meta name="twitter:description" content="${escapeHtmlAttr(description)}" />`
    );
  if (schemaJson) {
    lines.push(
      `<script type="application/ld+json" is:inline>${jsonForScriptTag(schemaJson)}</script>`
    );
  }
  if (organizationSchemaJson) {
    lines.push(
      `<script type="application/ld+json" is:inline>${jsonForScriptTag(organizationSchemaJson)}</script>`
    );
  }
  for (const tag of extraTags) {
    if (tag) lines.push(tag);
  }
  return lines.join("\n");
}

function jsonForScriptTag(value) {
  const json = typeof value === "string" ? value : JSON.stringify(value);
  return String(json).replaceAll("</", "<\\/");
}

function attr(value) {
  return JSON.stringify(String(value ?? ""));
}

function escapeHtmlAttr(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function escapeHtmlText(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

function indent(value, spaces) {
  if (!value) return "";
  const pad = " ".repeat(spaces);
  return value
    .split("\n")
    .map((line) => (line ? `${pad}${line}` : ""))
    .join("\n");
}

function lcFirst(value) {
  return value ? value[0].toLowerCase() + value.slice(1) : value;
}
