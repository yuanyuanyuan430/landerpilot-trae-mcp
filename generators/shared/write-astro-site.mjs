import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve } from "node:path";
import { normalizeTheme, renderTailwindGlobalCss } from "./theme.mjs";
import { normalizeRoute, routeToOutputPage } from "./slug.mjs";

export function writeAstroSite(siteDir, result, options = {}) {
  const pagesDir = join(siteDir, "src", "pages");
  const pagesRoot = resolve(pagesDir);
  mkdirSync(pagesDir, { recursive: true });
  const normalizedPages = normalizePages(result.pages || [], pagesDir, pagesRoot);
  cleanGeneratedPages(pagesDir);

  const mergedTheme = mergeThemeSources(result?.theme, options?.theme);
  const theme = normalizeTheme(mergedTheme);
  if (!theme.industry && mergedTheme.industry) theme.industry = mergedTheme.industry;
  const componentCss = [];
  const preparedPages = normalizedPages.map((page) => {
    if (page.astroBody) {
      // New component-based path: page already carries a complete .astro
      // source string. Section components ship their own scoped styles, so
      // we don't run the legacy extractStyleBlocks → @layer components route.
      return { ...page, astroBody: page.astroBody };
    }
    const extracted = extractStyleBlocks(page.content || "");
    componentCss.push(...extracted.styles);
    return { ...page, content: ensureDefaultFaviconLink(extracted.html) };
  });
  writeGlobalCss(siteDir, theme, componentCss);
  writeDefaultFavicon(siteDir, result.title || "LanderPilot Site");

  const pages = [];
  for (const page of preparedPages) {
    mkdirSync(dirname(page.astroPath), { recursive: true });
    if (page.astroBody) {
      writeFileSync(page.astroPath, page.astroBody);
    } else {
      const content = asAstroPage(page.content || "", {
        blueprint: result.blueprint,
        route: page.route,
        cssImport: cssImportPath(page.astroPath, siteDir),
      });
      writeFileSync(page.astroPath, content);
    }
    pages.push(page.outputPage);
  }

  const manifest = writeSiteManifest(siteDir, {
    title: result.title || "LanderPilot Site",
    pages,
    blueprint: result.blueprint || "custom",
    variant: result.variant || "default",
    summary: result.summary || {},
  });
  writeGenerationArtifacts(siteDir, { result, input: options.input, theme });
  return { pages, manifest };
}

function mergeThemeSources(...sources) {
  const merged = {};
  for (const src of sources) {
    if (!src || typeof src !== "object") continue;
    for (const [key, value] of Object.entries(src)) {
      if (value === undefined) continue;
      if (key === "tokens" && value && typeof value === "object") {
        merged.tokens = { ...(merged.tokens || {}), ...value };
      } else {
        merged[key] = value;
      }
    }
  }
  return merged;
}

function normalizePages(rawPages, pagesDir, pagesRoot) {
  const seenRoutes = new Set();
  return rawPages.map((page) => {
    const route = normalizeRoute(page.route);
    if (seenRoutes.has(route)) {
      throw new Error(`Duplicate LanderPilot route generated: ${route}`);
    }
    seenRoutes.add(route);
    const outputPage = routeToOutputPage(route);
    const astroPath = route === "index" ? join(pagesDir, "index.astro") : join(pagesDir, route, "index.astro");
    assertPathInside(astroPath, pagesRoot);
    return { ...page, route, outputPage, astroPath };
  });
}

function assertPathInside(child, parent) {
  const rel = relative(resolve(parent), resolve(child));
  if (rel && (rel.startsWith("..") || isAbsolute(rel))) {
    throw new Error(`Generated page path escapes src/pages: ${child}`);
  }
}

function cleanGeneratedPages(pagesDir) {
  if (!existsSync(pagesDir)) return;
  for (const entry of readdirSync(pagesDir, { withFileTypes: true })) {
    const path = join(pagesDir, entry.name);
    if (entry.isFile() && entry.name.endsWith(".astro")) {
      rmSync(path, { force: true });
    } else if (entry.isDirectory()) {
      rmSync(path, { recursive: true, force: true });
    }
  }
}

function asAstroPage(html, metadata) {
  const { cssImport, ...pageMetadata } = metadata;
  return [
    "---",
    "// Generated by LanderPilot. Edit source data under .ganhuo/ before regenerating.",
    `import ${JSON.stringify(cssImport)};`,
    `const landerpilot = ${JSON.stringify(pageMetadata, null, 2)};`,
    "void landerpilot;",
    "---",
    "",
    html.trim(),
    "",
  ].join("\n");
}

function extractStyleBlocks(html) {
  const styles = [];
  const withoutStyles = String(html).replace(/<style\b[^>]*>([\s\S]*?)<\/style>/gi, (_match, css) => {
    const normalized = String(css || "").trim();
    if (normalized) styles.push(normalized);
    return "";
  });
  return { html: withoutStyles, styles };
}

function ensureDefaultFaviconLink(html) {
  const source = String(html || "");
  if (/<link\b[^>]*\brel=["'][^"']*\b(?:icon|shortcut icon)\b[^"']*["'][^>]*>/i.test(source)) {
    return source;
  }
  return source.replace(
    /<\/head>/i,
    '<link rel="icon" type="image/svg+xml" href="/favicon.svg">\n</head>'
  );
}

function writeDefaultFavicon(siteDir, title) {
  const publicDir = join(siteDir, "public");
  const faviconPath = join(publicDir, "favicon.svg");
  if (existsSync(faviconPath)) return;
  mkdirSync(publicDir, { recursive: true });
  const initials = faviconInitials(title);
  writeFileSync(
    faviconPath,
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="#2563eb"/><text x="32" y="39" text-anchor="middle" font-family="ui-sans-serif,system-ui,-apple-system,BlinkMacSystemFont,Segoe UI,sans-serif" font-size="22" font-weight="800" fill="#fff">${escapeXml(initials)}</text></svg>\n`
  );
}

function faviconInitials(title) {
  const words = String(title || "LP")
    .replace(/[^a-z0-9\s-]/gi, " ")
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  const initials = words.length >= 2 ? `${words[0][0]}${words[1][0]}` : (words[0] || "LP").slice(0, 2);
  return initials.toUpperCase();
}

function escapeXml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function writeGlobalCss(siteDir, theme, componentCss) {
  const stylesDir = join(siteDir, "src", "styles");
  mkdirSync(stylesDir, { recursive: true });
  writeFileSync(join(stylesDir, "global.css"), renderTailwindGlobalCss(theme, { componentCss: uniqueCss(componentCss) }));
}

function uniqueCss(componentCss) {
  const seen = new Set();
  const out = [];
  for (const css of componentCss) {
    const normalized = String(css || "").trim();
    if (!normalized || seen.has(normalized)) continue;
    seen.add(normalized);
    out.push(normalized);
  }
  return out;
}

function cssImportPath(astroPath, siteDir) {
  const target = join(siteDir, "src", "styles", "global.css");
  const rel = relative(dirname(astroPath), target).replaceAll("\\", "/");
  return rel.startsWith(".") ? rel : `./${rel}`;
}

function writeSiteManifest(siteDir, value) {
  const manifestDir = join(siteDir, "public", ".ganhuo");
  mkdirSync(manifestDir, { recursive: true });
  const previous = readJson(join(manifestDir, "site.json"));
  const manifest = {
    kind: "static-site",
    title: value.title,
    entry: "index.html",
    pages: value.pages,
    framework: "astro",
    template: value.blueprint,
    templateVariant: value.variant,
    createdBy: "landerpilot",
    summary: value.summary,
    deployment: deploymentContract(),
    updatedAt: new Date().toISOString(),
  };
  if (previous.createdAt) manifest.createdAt = previous.createdAt;
  writeFileSync(join(manifestDir, "site.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  return manifest;
}

function deploymentContract() {
  return {
    targetKind: "static-site",
    framework: "astro",
    outputDir: "dist",
    artifactKind: "static-files",
    preferredProvider: "cloudflare",
    remoteStateRequired: true,
    userConfirmationRequired: true,
    localManifestIsNotRemoteTruth: true,
    handoffPath: ".ganhuo/deployment-handoff.json",
  };
}

function writeGenerationArtifacts(siteDir, value) {
  const dir = join(siteDir, ".ganhuo");
  mkdirSync(dir, { recursive: true });
  if (value.input) {
    writeFileSync(join(dir, "landerpilot-input.json"), `${JSON.stringify(value.input, null, 2)}\n`);
  }
  writeFileSync(
    join(dir, "site-plan.json"),
    `${JSON.stringify(
      {
        blueprint: value.result.blueprint,
        variant: value.result.variant,
        title: value.result.title,
        description: value.result.description,
        summary: value.result.summary,
        pages: (value.result.pages || []).map((page) => ({
          route: normalizeRoute(page.route),
          output: routeToOutputPage(page.route),
          title: page.title || null,
        })),
        generatedAt: new Date().toISOString(),
      },
      null,
      2
    )}\n`
  );
  writeFileSync(join(dir, "theme.json"), `${JSON.stringify(value.theme, null, 2)}\n`);
}

function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return {};
  }
}
