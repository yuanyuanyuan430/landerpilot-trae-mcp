import sanitizeHtml from "sanitize-html";

const options = {
  allowedTags: [
    "p",
    "h2",
    "h3",
    "h4",
    "h5",
    "h6",
    "blockquote",
    "ul",
    "ol",
    "li",
    "strong",
    "b",
    "em",
    "i",
    "u",
    "s",
    "code",
    "pre",
    "a",
    "abbr",
    "br",
    "hr",
    "figure",
    "figcaption",
    "img",
    "table",
    "thead",
    "tbody",
    "tfoot",
    "tr",
    "th",
    "td",
    "sup",
    "sub",
    "mark",
    "kbd",
    "samp",
    "time",
  ],
  allowedAttributes: {
    a: ["href", "title"],
    img: [
      "src",
      "alt",
      "title",
      { name: "loading", values: ["lazy", "eager"] },
      { name: "decoding", values: ["async", "sync", "auto"] },
    ],
    time: ["datetime"],
  },
  allowedSchemes: ["http", "https", "mailto", "tel"],
  allowProtocolRelative: false,
  nonTextTags: [
    "style",
    "script",
    "textarea",
    "option",
    "xmp",
    "noscript",
    "noembed",
    "noframes",
    "iframe",
    "object",
    "embed",
    "svg",
    "math",
    "template",
  ],
};

export function sanitizeBlogHtml(value) {
  return sanitizeHtml(String(value ?? ""), options);
}
